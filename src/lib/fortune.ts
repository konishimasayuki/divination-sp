function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

export function todaysFortune(seed: string, date = new Date()) {
  const day = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
  const h = hash(`${day}:${seed}`);
  const pick = (arr: string[], salt: number) => arr[(h + salt * 7919) % arr.length];
  return {
    stars: 3 + (h % 3), // 3〜5
    texts: {
      all: pick(TEXTS.all, 1),
      love: pick(TEXTS.love, 2),
      work: pick(TEXTS.work, 3),
      money: pick(TEXTS.money, 4),
    },
    color: pick(COLORS, 5),
    item: pick(ITEMS, 6),
  };
}
